import type { Mission, MissionEntry, MissionTask } from '../generated/prisma/client.js';
import { planTasks, type Plan } from './plan-schema.js';

const MAX_LENGTH = 60_000;

/** Markdown-safe text: no accidental headings, lists or emphasis. */
function esc(value: string) {
  return value
    .replace(/([\\`*_{}[\]()#+.!|>~-])/g, '\\$1')
    .replace(/\r?\n/g, ' ');
}

function dataOf(entry: MissionEntry): Record<string, unknown> {
  try {
    return JSON.parse(entry.dataJson) as Record<string, unknown>;
  } catch {
    return {};
  }
}

/** The pull request body: goal, tasks, checks, decisions, usage (§6.4). */
export function prBody(
  mission: Pick<Mission, 'id' | 'title' | 'costUsd' | 'approvedVersion'>,
  plan: Plan,
  tasks: MissionTask[],
  entries: MissionEntry[],
) {
  const rows = new Map(tasks.map((task) => [task.key, task]));
  const decisions = entries.filter((entry) => entry.kind === 'decision');
  const checks = [...entries].reverse().find((entry) => entry.kind === 'checks');
  const turns = entries.filter((entry) => entry.kind === 'turn').length;

  const parts: string[] = [];
  parts.push(`## Goal\n\n${esc(plan.goal)}`);

  const taskLines: string[] = ['## Tasks', ''];
  for (const planned of planTasks(plan)) {
    const row = rows.get(planned.key);
    const title = planned.title ?? planned.key;
    if (row?.status === 'skipped') {
      const report = row.reportJson
        ? (JSON.parse(row.reportJson) as { summary?: string })
        : null;
      taskLines.push(
        `- [ ] ~~**${planned.key}**~~ ${esc(title)} — skipped${report?.summary ? `: ${esc(report.summary)}` : ''}`,
      );
      continue;
    }
    taskLines.push(`- [${row?.status === 'done' ? 'x' : ' '}] **${planned.key}** ${esc(title)}`);
    for (const criterion of planned.acceptance) {
      taskLines.push(`  - ${esc(criterion)}`);
    }
  }
  parts.push(taskLines.join('\n'));

  if (checks) {
    const data = dataOf(checks) as {
      results?: { name: string; ok: boolean; durationMs?: number }[];
    };
    const lines = ['## Checks', '', '| Command | Result |', '|---|---|'];
    for (const result of data.results ?? []) {
      lines.push(
        `| ${esc(result.name)} | ${result.ok ? '✅' : '❌'} ${result.durationMs ? `${Math.round(result.durationMs / 1000)} s` : ''} |`,
      );
    }
    parts.push(lines.join('\n'));
  }

  if (decisions.length) {
    const lines = ['## Decisions taken automatically', ''];
    for (const entry of decisions) {
      const data = dataOf(entry) as {
        question?: string;
        chosen?: string;
        reason?: string;
        violations?: unknown;
      };
      if (data.violations) continue;
      lines.push(
        `- **${esc(data.question ?? '?')}** → ${esc(data.chosen ?? '?')}${data.reason ? `. ${esc(data.reason)}` : ''}`,
      );
    }
    if (lines.length > 2) parts.push(lines.join('\n'));
  }

  const scope = decisions.filter((entry) => dataOf(entry).violations);
  if (scope.length) {
    const lines = ['## Scope changes accepted', ''];
    for (const entry of scope) {
      const data = dataOf(entry) as { reason?: string; chosen?: string };
      lines.push(`- ${esc(data.reason ?? data.chosen ?? 'scope change')}`);
    }
    parts.push(lines.join('\n'));
  }

  const sessions = tasks.reduce((sum, task) => sum + task.attempts + 1, 0) + turns;
  parts.push(
    `## Usage\n\nAgent sessions: ${sessions} · Cost: $${mission.costUsd.toFixed(2)} · Weekly share used (estimate)`,
  );

  parts.push(
    `---\n\nMission #${mission.id} · plan v${mission.approvedVersion ?? 1} · generated by algo-agent`,
  );

  let body = parts.join('\n\n');
  if (body.length > MAX_LENGTH) {
    body = `${body.slice(0, MAX_LENGTH - 20)}
(truncated)`;
  }
  return body;
}
